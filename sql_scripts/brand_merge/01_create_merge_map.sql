/* ============================================================
 * dim.dim_brand_merge_map —— 品牌重复合并的权威映射表（单一事实源）
 *
 * keep_id  = 合并后保留的 brand_id_std
 * merge_id = 退役的 brand_id_std（其别名并入 keep，state 置 0，存量 brandid remap 成 keep）
 *
 * 主键 = merge_id，INSERT 即 upsert，可重复执行。
 * 后续 03_merge_dim.py / 04_sync_dwd_l2.py 全部以本表为准。
 * 依据见《品牌需要处理的.md》。
 * ============================================================ */

CREATE TABLE IF NOT EXISTS dim.dim_brand_merge_map (
    `merge_id`  BIGINT      NOT NULL COMMENT '退役的 brand_id_std',
    `keep_id`   BIGINT      NOT NULL COMMENT '保留的 brand_id_std',
    `brand`     VARCHAR(256) NULL    COMMENT '品牌可读名（仅备注）',
    `reason`    VARCHAR(512) NULL    COMMENT '合并依据',
    `merged_at` DATETIME     NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE = OLAP
PRIMARY KEY (`merge_id`)
COMMENT '品牌重复合并映射（keep <- merge）'
DISTRIBUTED BY HASH(`merge_id`) BUCKETS 4
PROPERTIES ("replication_num" = "1", "enable_persistent_index" = "true");

